const idNames: Record<string, string> = {
  mt_IHipFGTFEY: '用点图整理分数测量数据',
}
export function topicName(topic: Topic, locale: Locale = browserLocale()) {
  if (locale === 'en') return topic.name
  return (
    topic.translations?.['zh-CN'].name ??
    idNames[topic.id] ??
    names[topic.name.replace(/ \(age \d+\+\)$/, '')] ??
    topic.name
  )
}
export function ageLabel(topic: Topic, locale: Locale = browserLocale()) {
  return topic.ageRangeStart != null && topic.ageRangeEnd != null
    ? translateText('{{v0}}–{{v1}} 岁', locale, {
        v0: topic.ageRangeStart,
        v1: topic.ageRangeEnd,
      })
    : translateText('年龄不限', locale)
}
